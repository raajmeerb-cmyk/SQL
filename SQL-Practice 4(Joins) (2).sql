   SCENARIO: AIRLINE RESERVATION SYSTEM
   Tables: Airlines -> Flights -> Bookings
   Focus: JOINS integrated with GROUP BY and HAVING
   ============================================================ */


/* ------------------------------------------------------------
   TABLE 1: Airlines (Parent table)
   ------------------------------------------------------------ */

CREATE TABLE Airlines (
    airline_id INT PRIMARY KEY,
    airline_name VARCHAR(50) NOT NULL UNIQUE,
    country VARCHAR(50) DEFAULT 'India',
    established_year INT CHECK (established_year >= 1950)
);

