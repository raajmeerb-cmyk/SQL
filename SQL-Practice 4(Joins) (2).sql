/* ============================================================
   15 QUESTIONS
   ============================================================ */

-- Q1. List every flight along with the name of the airline operating it.
select flight_number as flights, airline_name as airlines
from flights
inner join airlines
on flights.airline_id = airlines.airline_id;

-- Q2. Find the total number of bookings for each flight.
select f.flight_id,f.flight_number,count(b.booking_id) as total_bookings
from flights f
inner join bookings b 
on f.flight_id = b.flight_id
group by f.flight_id;

-- Q3. Find flights that have more than 1 booking.
select f.flight_id,f.flight_number,count(b.booking_id) as total_bookings
from flights f 
inner join bookings b 
on f.flight_id = b.flight_id
group by f.flight_id
having total_bookings >1;

-- Q4. Find the total revenue (sum of fare) generated by each flight.
select f.flight_id,f.flight_number,sum(b.fare) as total_fare
from flights f 
inner join bookings b 
on f.flight_id = b.flight_id
group by f.flight_id;

-- Q5. Find flights whose total revenue is more than 10000.
select f.flight_id,f.flight_number,sum(b.fare) as total_revenue
from flights f 
inner join bookings b 
on f.flight_id = b.flight_id
group by f.flight_id
having total_revenue > 10000;
 
-- Q6. Find the total revenue generated by each airline (joining all three tables).
select a.airline_id,a.airline_name,sum(b.fare) as total_revenue
from airlines a 
inner join flights f 
on a.airline_id = f.airline_id
inner join bookings b 
on f.flight_id = b.flight_id
group by a.airline_id; 

-- Q7. Find airlines whose total revenue is more than 15000.
select a.airline_id,a.airline_name,sum(b.fare) as total_revenue
from airlines a 
inner join flights f 
on a.airline_id = f.airline_id
inner join bookings b 
on f.flight_id = b.flight_id 
group by a.airline_id
having total_revenue > 15000;

-- Q8. Find the average fare paid per booking for each airline.
select a.airline_id,a.airline_name,round(avg(b.fare),2) as average_booking
from airlines a 
inner join flights f 
on a.airline_id = f.airline_id
inner join bookings b 
on f.flight_id = b.flight_id
group by a.airline_id;


-- Q9. Find airlines where the average fare is greater than 6000.
select a.airline_id,a.airline_name,round(avg(b.fare),2) as average_booking
from airlines a 
inner join flights f 
on a.airline_id = f.airline_id
inner join bookings b 
on f.flight_id = b.flight_id
group by a.airline_id
having average_booking > 6000;

-- Q10. Find the number of bookings made in each seat class (Economy vs Business).
select b.booking_id,b.seat_class,count(b.seat_class) as total_bookings
from bookings b
group by b.booking_id;

-- Q11. Find the total number of flights operated by each airline.
select airline_name,count(flight_id) as total_numbers
from airlines
inner join flights
on airlines.airline_id = flights.airline_id
group by airline_name;

-- Q12. Find airlines that operate more than 1 flight.
select airline_name,count(flight_id) as total_flights
from airlines
inner join flights
on airlines.airline_id = flights.flight_id
group by airline_name
having total_flights > 1;

-- Q13. Find the highest fare paid for each flight.
select flight_number,sum(fare) as total_fare
from flights
inner join bookings
on flights.flight_id = bookings.flight_id
group by flight_number
order by sum(fare) desc
limit 1;

-- Q14. Find flights where the highest fare paid is 10000 or more.
select flight_number ,max(fare) as highest_fare
from flights
inner join bookings
on flights.flight_id = bookings.flight_id
group by flight_number
having highest_fare > 10000;

-- Q15. Find each airline's average distance covered by its flights, showing
--      only airlines whose average flight distance is more than 1200 km.
select airline_name,avg(distance_km) as average_distance
from airlines
inner join flights
on airlines.airline_id = flights.flight_id
group by airline_name
having average_distance >1200;
